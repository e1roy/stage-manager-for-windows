func TestButtonOf(t *testing.T) {
	chrome := catalog.Window{Title: "AOEM : Code Review - Google Chrome", Exe: `C:\Program Files\Google\Chrome\Application\chrome.exe`, PID: 10}
	weixin := catalog.Window{Title: "微信", Exe: `C:\Program Files\Tencent\Weixin\Weixin.exe`, PID: 20}
	idea := catalog.Window{Title: "NewKing – MailMgr.java", Exe: `C:\Users\me\AppData\Local\Programs\IntelliJ IDEA\bin\idea64.exe`, PID: 30}
	tool := catalog.Window{Title: "search_xls_gui.exe", Exe: `D:\tools\search_xls_gui.exe`, PID: 0x20df4}
	cases := []struct {
		button winapi.TaskbarButton
		w      catalog.Window
		name   string
		want   bool
	}{
		{winapi.TaskbarButton{Name: "Google Chrome - 2 个运行窗口 已固定", AppID: "Chrome"}, chrome, "Google Chrome", true},
		{winapi.TaskbarButton{Name: "Google Chrome - 2 个运行窗口 已固定", AppID: "Chrome"}, weixin, "Weixin", false},
		// WeChat's pinned shortcut gives it an ID of the shell's; its window
		// has the name the button reads out.
		{winapi.TaskbarButton{Name: "微信 - 1 个运行窗口 已固定", AppID: "Microsoft.AutoGenerated.{5FD21F2E-64C7-8F20-F9FB-2514D0A0A64B}"}, weixin, "Weixin", true},
		{winapi.TaskbarButton{Name: "微信 - 1 个运行窗口 已固定", AppID: "Microsoft.AutoGenerated.{5FD21F2E-64C7-8F20-F9FB-2514D0A0A64B}"}, chrome, "Google Chrome", false},
		{winapi.TaskbarButton{Name: "IntelliJ IDEA - 1 个运行窗口 已固定", AppID: `C:\Users\me\AppData\Local\Programs\IntelliJ IDEA\bin\idea64.exe`}, idea, "IntelliJ IDEA", true},
		{winapi.TaskbarButton{Name: "Notepad++ - 1 个运行窗口 已固定", AppID: `{6D809377-6AF0-444B-8957-A3773F02200E}\Notepad++\notepad++.exe`}, idea, "IntelliJ IDEA", false},
		{winapi.TaskbarButton{Name: "search_xls_gui.exe - 1 个运行窗口", AppID: "*PID00020df4"}, tool, "search_xls_gui", true},
		{winapi.TaskbarButton{Name: "search_xls_gui.exe - 1 个运行窗口", AppID: "*PID00020df4"}, chrome, "Google Chrome", false},
		// A pinned app without windows has no thumbnails.
		{winapi.TaskbarButton{Name: "Microsoft Edge 已固定", AppID: "MSEdge"}, chrome, "Google Chrome", false},
	}
	for _, c := range cases {
		if got := buttonOf(c.button, c.w, c.name); got != c.want {
			t.Errorf("buttonOf(%q, %q) = %v, want %v", c.button.Name, c.w.Title, got, c.want)
		}
	}
}

func TestButtonAt(t *testing.T) {
	buttons := []winapi.TaskbarButton{
		{Name: "a", Rect: winapi.Rect{Left: 0, Top: 100, Right: 50, Bottom: 150}},
		{Name: "b", Rect: winapi.Rect{Left: 60, Top: 100, Right: 110, Bottom: 150}},
	}
	for _, c := range []struct {
		p    winapi.Point
		want string
	}{
		{winapi.Point{X: 70, Y: 120}, "b"},
		{winapi.Point{X: 54, Y: 120}, "a"}, // between the two
		{winapi.Point{X: 57, Y: 120}, "b"},
	} {
		if b, ok := buttonAt(buttons, c.p); !ok || b.Name != c.want {
			t.Errorf("buttonAt(%v) = %q, want %q", c.p, b.Name, c.want)
		}
	}
	if _, ok := buttonAt(buttons, winapi.Point{X: 70, Y: 20}); ok {
		t.Error("buttonAt above the taskbar found a button")
	}
}
